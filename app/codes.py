"""名古屋市 地震ハザードマップ（震度・液状化）の値の読み方。

出典: 名古屋市オープンデータ「地震ハザードマップ」（CC BY 4.0・令和7年8月時点）
想定: 平成26年2月公表の南海トラフ地震の被害想定。
      「あらゆる可能性を考慮した最大クラス」（千年に一度あるいはそれより低頻度）。

【震度】I_S は計測震度。気象庁の震度階級の境界でそのまま区切れる。
【液状化】PL は液状化指数（PL値）。標準的な区分は下の LIQ_RANK。

**PL の負の値について（重要・推測で埋めない）**
  実データに現れる負の値は **-1.0（4,930メッシュ）と -6.6（30,665メッシュ）の2種類だけ**で、
  どちらも PL と S が同じ値になっている＝計算値ではなく欠測コード。
  配布元のメタデータにも市の公開資料にも、この2つの定義は見つからなかった（2026-09-12 調査）。

  そこで分布を実測した:
    -6.6 の 94.2%、-1.0 の 87.9% が市の**東側**（熱田台地・東部丘陵＝洪積台地）。
    有効値の 69.9% は**西側**（沖積低地）。
  → 負の値は「液状化の判定対象になっていない地盤」を指すとみて扱う。

  **-1.0 と -6.6 の違いは分からないので、区別せず「判定対象外」とまとめる。**
  画面でも「対象外」と「液状化しない（PL=0）」を必ず分けて表示する。
  名古屋市に確認が取れたら、ここを直すこと。
"""

#: 計測震度 → 気象庁の震度階級（境界は気象庁の定義そのまま）
def shindo_kaikyu(i_s: float) -> str:
    if i_s < 0.5: return "震度0"
    if i_s < 1.5: return "震度1"
    if i_s < 2.5: return "震度2"
    if i_s < 3.5: return "震度3"
    if i_s < 4.5: return "震度4"
    if i_s < 5.0: return "震度5弱"
    if i_s < 5.5: return "震度5強"
    if i_s < 6.0: return "震度6弱"
    if i_s < 6.5: return "震度6強"
    return "震度7"


#: 震度階級ごとに「何が起きるか」（気象庁 震度階級関連解説表の要点）
SHINDO_MEANING = {
    "震度5弱": "物につかまりたいと感じる。棚の食器や本が落ちることがある。",
    "震度5強": "物につかまらないと歩くことが難しい。補強されていないブロック塀が崩れることがある。",
    "震度6弱": "立っていることが困難になる。耐震性の低い木造建物は、傾いたり倒れたりするものがある。",
    "震度6強": "はわないと動くことができず、飛ばされることもある。耐震性の低い木造建物は倒れるものが多くなる。",
    "震度7": "耐震性の低い木造建物は傾くものや倒れるものがさらに多くなる。耐震性の高い建物でも傾くことがある。",
}

#: PL値（液状化指数）の区分。土木学会等で使われる標準的な区分
LIQ_RANK = (
    (0.0,  "液状化の危険度は低い", "PL = 0"),
    (5.0,  "液状化の危険度は低い", "0 < PL ≦ 5"),
    (15.0, "液状化の危険度が高い", "5 < PL ≦ 15"),
    (1e9,  "液状化の危険度が極めて高い", "PL > 15"),
)

#: PL が負のときの扱い。値は -1.0 と -6.6 の2種類だけで、意味の定義が公開されていない
LIQ_OUT_OF_SCOPE = "液状化の判定対象外"
LIQ_OUT_OF_SCOPE_NOTE = (
    "この地点は液状化の判定対象になっていません。"
    "名古屋市の東部（熱田台地・東部丘陵などの台地）に多く分布します。"
    "「液状化しない」と判定されたわけではなく、判定の対象に入っていない、という意味です。"
)


def liq_rank(pl: float):
    """PL値 → (区分名, 範囲の表記)。負なら判定対象外を返す。"""
    if pl < 0:
        return LIQ_OUT_OF_SCOPE, ""
    if pl == 0:
        return "液状化の危険度なし", "PL = 0"
    for hi, name, span in LIQ_RANK:
        if pl <= hi:
            return name, span
    return LIQ_RANK[-1][1], LIQ_RANK[-1][2]
